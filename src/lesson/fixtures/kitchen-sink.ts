/**
 * A tiny topic whose steps use every one of the 43 commands at least once, with paths that
 * resolve at the step where they run. Not a lesson: it exists so the reducer, stage and lint
 * tests have full command coverage from one fixture. Validated by fixtures.test.ts.
 */
import {
  topic,
  scene,
  step,
  alice,
  bob,
  carol,
  server,
  device,
  board,
  rec,
  list,
  table,
  row,
  meter,
  bytes,
  text,
  spawn,
  remove,
  removeBoard,
  layout,
  tick,
  skew,
  offline,
  online,
  status,
  note,
  set,
  patch,
  insert,
  del,
  move,
  sort,
  annotate,
  unannotate,
  view,
  send,
  deliver,
  drop,
  duplicate,
  relay,
  highlight,
  callout,
  conflict,
  compare,
  same,
  check,
  cross,
  clearMarks,
  unmark,
  expect,
  bad,
  good,
  tomb,
  apply,
  merge,
  ref,
  crdt,
  seed,
  lww,
  pncounter,
  orSet,
  rga,
  doc,
  S,
  allSame,
  regex,
} from '@/lesson/builders'

export const kitchenSinkTopic = topic({
  id: 'kitchen-sink',
  title: 'Kitchen sink',
  goal: 'Exercise every DSL command once (a test fixture, not a lesson).',
  whenToUse: ['Reducer, stage and lint tests that need full command coverage.'],
  whenNotToUse: ['Teaching anything.'],
  realWorld: 'The test suite.',
  scenes: [
    scene(
      'primitives',
      {
        layout: 'row',
        clock: { show: true },
        actors: [
          alice({
            holds: {
              doc: rec({ title: 'Q3 plan', owner: 'Bob' }),
              list: list(['bread', 'milk']),
              id: bytes('9c017e5502a1e4712d66c0158af34102'),
              tbl: table(
                ['how', 'use'],
                [
                  row('r1', { how: 'replaces', use: 'LWW' }),
                  row('r2', { how: 'adds', use: 'counter' }),
                ],
              ),
              gauge: meter(6, 24, 'values read'),
            },
          }),
          bob({ holds: { doc: rec({ title: 'Q3 plan' }) } }),
          server(),
        ],
        boards: [board('rule', text('merge(a, b) = max(a, b)'), { label: 'rule' })],
      },
      [
        step(
          's01',
          'Set writes a value; patch writes only the sidecar.',
          set('alice.doc.title', 'Q3 plan v2'),
          patch('alice.doc.title', { ts: 1, node: 'alice' }),
          expect('alice.doc.title', 'Q3 plan v2'),
          expect('alice.doc.title@ts', 1),
        ),
        step(
          's02',
          'Insert, move, delete and sort reorder a list.',
          insert('alice.list', 'eggs', { index: 1 }),
          move('alice.list[milk]', 0),
          del('alice.list[bread]', { tombstone: true }),
          sort('alice.list', ['value']),
          expect('alice.list', ['eggs', 'milk']),
        ),
        step(
          's03',
          'Annotate, view and unannotate work on bytes.',
          annotate('alice.id', 0, 6, 'time', { tone: 'change', id: 'time' }),
          annotate('alice.id', 48, 52, 'version', { unit: 'bit', id: 'ver' }),
          view('alice.id', 'bits', [6, 9]),
          unannotate('alice.id', 'time'),
          expect('alice.id[0..6]', '9c017e5502a1'),
        ),
        step(
          's04',
          'Send carries a snapshot; deliver lands it.',
          send('alice', 'server', ref('alice.doc'), {
            id: 'm1',
            label: 'save',
            into: 'server.doc',
          }),
          deliver('m1'),
          expect('server.doc.title', 'Q3 plan v2'),
        ),
        step(
          's05',
          'A fan-out sends one copy per recipient; one copy is dropped.',
          send('server', ['alice', 'bob'], 'ack', { id: 'm2' }),
          deliver('m2@alice'),
          drop('m2@bob'),
        ),
        step(
          's06',
          'Duplicate splits a retry off; relay forwards at the hub.',
          send('alice', 'server', 'hello', { id: 'm3' }),
          duplicate('m3', 'm3-retry'),
          relay('m3', ['bob']),
          deliver('m3@bob'),
          drop('m3-retry'),
        ),
        step(
          's07',
          'Spawn, layout, status and skew change the cast and the clock.',
          spawn(carol()),
          layout('hub', { hub: 'server' }),
          offline('carol'),
          online('carol'),
          status('carol', 'busy'),
          skew('carol', 5),
          tick(2),
          expect('carol@clock', 7),
        ),
        step(
          's08',
          'Note upserts a rule card; removeBoard and remove take things away.',
          note('rule', 'max(a, b) is commutative', { tone: 'info' }),
          note('law', 'merge(a, a) = a'),
          removeBoard('law'),
          status('carol', null),
          remove('carol'),
        ),
        step(
          's09',
          'Marks: highlight, callout, conflict, compare, check and cross.',
          highlight(['alice.doc.title', 'bob.doc.title'], { tone: 'warn' }),
          callout('alice.doc.title', 'newer', { tone: 'info', sticky: true, id: 'c1' }),
          conflict('alice.doc.title', 'bob.doc.title'),
          compare(['alice.doc.title', 'bob.doc.title'], { expect: 'different' }),
          check('alice.doc.title'),
          cross('bob.doc.title'),
          good('alice.doc'),
          bad('bob.doc', 'stale'),
          tomb('alice.list[bread]'),
        ),
        step(
          's10',
          'Unmark removes one mark; clearMarks removes them all.',
          unmark('c1'),
          clearMarks(),
        ),
      ],
    ),
    scene('crdt', { layout: 'pair', clock: { show: true }, actors: [alice(), bob()] }, [
      step(
        's01',
        'Init creates a replica per actor; doc composes parts.',
        crdt.init(['alice', 'bob'], 'status', 'lww-register', { seed: [seed('set', 'Offline')] }),
        crdt.init(['alice', 'bob'], 'likes', 'pn-counter'),
        crdt.init(['alice', 'bob'], 'cart', 'or-set'),
        crdt.init(['alice', 'bob'], 'text', 'rga', { display: 'text' }),
        crdt.doc(
          ['alice', 'bob'],
          'list',
          { title: S.lww(), items: S.set(S.map({ name: S.lww(), qty: S.pn() })) },
          { seed: [seed.at('title', 'set', 'Groceries')] },
        ),
        expect('alice.status', 'Offline'),
        expect('alice.list.title', 'Groceries'),
      ),
      step(
        's02',
        'Update runs the real CRDT; every op gets an id.',
        tick(),
        lww('status').set('alice', 'Busy'),
        pncounter('likes').inc('alice', 2),
        pncounter('likes').dec('bob'),
        orSet('cart').add('alice', 'milk'),
        rga('text').type('alice', 'HEAD', 'hi'),
        crdt.updateAt('alice', 'list', 'items', 'add', { name: 'milk' }),
        doc('list').at('items[alice:1].qty').inc('alice', 2),
        expect('alice.status@ts', 1),
        expect('alice.likes', 2),
        expect('bob.likes', -1),
        expect('alice.cart', ['milk']),
        expect('alice.text', 'hi'),
        expect('alice.list.items[alice:1].qty', 2),
      ),
      step(
        's03',
        'Send a state snapshot; merge applies it on arrival.',
        crdt.send('alice', 'bob', 'status', { id: 'm1', label: 'state' }),
        merge('m1'),
        expect('bob.status', 'Busy'),
      ),
      step(
        's04',
        'Broadcast flushes the outbox as op messages; apply delivers one.',
        crdt.broadcast('alice', 'likes', { to: ['bob'] }),
        apply('alice:1@bob'),
        expect('bob.likes', 1),
      ),
      step(
        's05',
        'Merge and sync are the instant forms.',
        crdt.merge('bob', 'alice', 'cart'),
        crdt.sync('alice', 'bob', 'text'),
        crdt.sync('alice', 'bob', 'list'),
        same('alice.cart', 'bob.cart'),
        same('alice.text', 'bob.text'),
        allSame('list', ['alice', 'bob']),
      ),
      step(
        's06',
        'Gc drops tombstones up to a version every replica has seen.',
        rga('text').delete('alice', 'alice:2'),
        crdt.sync('alice', 'bob', 'text'),
        crdt.gc('alice', 'text', { upTo: { alice: 3, bob: 0 } }),
        expect('alice.text', 'h'),
      ),
      step(
        's07',
        'A delta send carries only the pending ops (simplified).',
        orSet('cart').add('bob', 'eggs'),
        crdt.send('bob', 'alice', 'cart', { id: 'm2', mode: 'delta' }),
        merge('m2'),
        expect('alice.cart', ['eggs', 'milk']),
      ),
    ]),
    scene(
      'after',
      null,
      [
        step(
          's01',
          "A scene can start from another scene's end.",
          clearMarks(),
          expect('bob.status', 'Busy'),
        ),
      ],
      { startFrom: 'crdt' },
    ),
    scene('regex', { layout: 'row', actors: [device('matcher', 'Matcher', { icon: 'laptop' })] }, [
      step(
        's01',
        'Regex init compiles the pattern and loads the input.',
        regex.init('matcher', 'ca*t', 'cat'),
        expect('matcher.text', 'cat'),
      ),
      step('s02', 'Advance runs the VM to the next match.', regex.advance('matcher', 'match')),
    ]),
  ],
})
